#!/usr/bin/env node
// Records the demo of the Docs MCP + Chain MCP agent: real functions on real Pharos mainnet contracts, each PINNED to a block so the chain's side
// can be replayed exactly later. The explanation comes from Developer Docs MCP at recording time (it is generated, so it is kept as recorded).
//   node scripts/docs-chain-demo.mjs        writes reports/docs-chain-demo.json
import { readFileSync, writeFileSync } from 'node:fs';
import { McpClient, PHAROS_CHAIN_MCP, PHAROS_DOCS_MCP } from '../lib/mcp.js';
import { runAgent } from '../lib/docs-chain.js';

const cases = JSON.parse(readFileSync(new URL('../agents/docs-chain-mcp-agent/examples/cases.json', import.meta.url), 'utf8'));
const chain = new McpClient(PHAROS_CHAIN_MCP);
const docs = new McpClient(PHAROS_DOCS_MCP, { retries: 1, timeoutMs: 50_000, retryTimeouts: false });
try {
  const out = [];
  for (const c of cases) {
    process.stderr.write(`${c.id} @ ${c.block} … `);
    const result = await runAgent({ chain, docs, contract: c.contract, signature: c.function, args: c.args, block: c.block });
    process.stderr.write(`${result.verdict.status.toUpperCase()} · ${result.chainCalls} Chain MCP + ${result.docsCalls} Docs MCP + ${result.rpcCalls} RPC calls · reads ${result.integrity.confirmed + result.integrity.resolved}/${result.integrity.checked} confirmed${result.interpretation?.value ? ` · ${result.interpretation.value.scaled}` : ''}\n`);
    out.push({ ...c, result });
  }
  const record = {
    recordedAt: new Date().toISOString(),
    network: { name: 'Pharos Pacific Mainnet', chainId: 1672 },
    note: 'Each case is pinned to a mainnet block. Replaying it asks Chain MCP the same questions at the same block. The explanation is generated by Docs MCP, so a replay may word it differently and ask for different checks.',
    cases: out,
  };
  writeFileSync(new URL('../reports/docs-chain-demo.json', import.meta.url), JSON.stringify(record, null, 1) + '\n');
  console.log(`wrote reports/docs-chain-demo.json: ${out.map((c) => `${c.id}=${c.result.verdict.status}`).join(', ')}`);
} finally {
  await chain.close();
  await docs.close();
}
